import { BODY_METHODS, scaffoldMapperIds, type RoutableOperation } from '../apispec/operationIds';
import { updateKaotoMetadata, type FlowFiles } from '../editor/flowFiles';
import { isGeneratedSchemaName, schemaFileName, serializeSchema, sourceOf, type SpecSchemaSource } from './specSchemas';

/**
 * The schemas ECHO attaches to the DataMappers of its route scaffolds (routeForOperation): the request
 * body as the source of the one before the call, the response as the target of the reply's. Each
 * becomes the openapi-*.schema.json file Attach Schema makes (so it follows the spec on Save), and a
 * Kaoto metadata entry for the step naming it, as Kaoto keeps one once a schema is attached.
 */

type Json = Record<string, unknown>;

const JSON_SCHEMA = 'JSON Schema';
const PRIMITIVE = 'Primitive';

/** An XSLT file as Kaoto writes one before anything is mapped: no template. */
export const EMPTY_XSL = `<?xml version="1.0" encoding="UTF-8"?>
<!-- This file is generated by Kaoto DataMapper. Do not edit. -->
<xsl:stylesheet version="3.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform">
  <xsl:output method="xml" indent="yes"/>
</xsl:stylesheet>
`;

/** Whether an XSLT file has mappings: Kaoto writes a template once something is mapped. */
export const hasMappings = (xsl: string | undefined) => !!xsl && /<xsl:template\b/.test(xsl);

/** The flow's DataMapper XSLT files (kaoto-datamapper-*.xsl) that have mappings. */
export async function mappedXslFiles(files: FlowFiles): Promise<Set<string>> {
  const names = (await files.list()).filter((name) => /^kaoto-datamapper-.+\.xsl$/.test(name));
  const mapped = new Set<string>();
  await Promise.all(names.map(async (name) => hasMappings(await files.read(name)) && mapped.add(name)));
  return mapped;
}

const document = (file?: string) => ({ type: file ? JSON_SCHEMA : PRIMITIVE, filePath: file ? [file] : [], fieldTypeOverrides: [] });

const schemaFile = (metadata: unknown, side: 'sourceBody' | 'targetBody'): string | undefined => {
  const path = (metadata as { [k: string]: { filePath?: unknown } } | undefined)?.[side]?.filePath;
  return Array.isArray(path) && typeof path[0] === 'string' ? path[0] : undefined;
};

/**
 * Writes the schema files and metadata the scaffold DataMappers of these operations' routes start
 * from (op.schemas), and takes the metadata off those whose operation has no such schema (any more).
 * A DataMapper with mappings is left as it is. Call it for the operations whose route was just made
 * or made again as a scaffold.
 */
export async function attachScaffoldSchemas(files: FlowFiles, operations: RoutableOperation[]): Promise<void> {
  if (!operations.length) return;
  const names = await files.list();
  const existing: Record<string, string | undefined> = {};
  for (const name of names) existing[name] = isGeneratedSchemaName(name) ? await files.read(name) : '';
  const mapped = await mappedXslFiles(files);
  /** The metadata for each step, with the side its schema is on; undefined: none from ECHO. */
  const entries: Record<string, { entry: Json; side: 'sourceBody' | 'targetBody' } | undefined> = {};

  const attach = async (stepId: string, schema: Json | undefined, side: 'sourceBody' | 'targetBody') => {
    const xsl = `${stepId}.xsl`;
    if (mapped.has(xsl)) return;
    if (!schema) {
      entries[stepId] = undefined;
      return;
    }
    const source = sourceOf(serializeSchema(schema)) as SpecSchemaSource;
    const name = schemaFileName(source, existing);
    const text = serializeSchema(schema);
    if (existing[name] !== text) await files.write(name, text);
    existing[name] = text;
    if (!names.includes(xsl)) await files.write(xsl, EMPTY_XSL);
    const entry = {
      xsltPath: xsl,
      sourceParameters: {},
      sourceBody: document(side === 'sourceBody' ? name : undefined),
      targetBody: document(side === 'targetBody' ? name : undefined),
      namespaceMap: {},
    };
    entries[stepId] = { entry, side };
  };

  for (const op of operations) {
    const ids = scaffoldMapperIds(op.operationId);
    if (BODY_METHODS.has(op.method.toUpperCase())) await attach(ids.request, op.schemas?.request, 'sourceBody');
    await attach(ids.response, op.schemas?.response, 'targetBody');
  }
  await updateKaotoMetadata(files, (metadata) => {
    for (const [stepId, made] of Object.entries(entries)) {
      if (made) {
        // Kept as it is when it already names this schema (Kaoto may have added to it).
        if (schemaFile(metadata[stepId], made.side) !== schemaFile(made.entry, made.side)) metadata[stepId] = made.entry;
      } else if (schemaFile(metadata[stepId], 'sourceBody') || schemaFile(metadata[stepId], 'targetBody')) {
        // ECHO's: Kaoto names the XSLT afresh when the DataMapper opens without one.
        delete metadata[stepId];
      }
    }
  });
}

/**
 * Takes away what attachScaffoldSchemas wrote for these operations' scaffold DataMappers, once their
 * routes are gone: the metadata, the XSLT files with nothing mapped, and the schema files no other
 * DataMapper uses.
 */
export async function forgetScaffoldSchemas(files: FlowFiles, operationIds: string[]): Promise<void> {
  if (!operationIds.length) return;
  const mapped = await mappedXslFiles(files);
  const names = await files.list();
  const stepIds = operationIds
    .flatMap((id) => Object.values(scaffoldMapperIds(id)))
    .filter((stepId) => !mapped.has(`${stepId}.xsl`));
  const dropped = new Set<string>();
  let used = new Set<string>();
  await updateKaotoMetadata(files, (metadata) => {
    for (const stepId of stepIds) {
      if (!metadata[stepId]) continue;
      for (const side of ['sourceBody', 'targetBody'] as const) {
        const file = schemaFile(metadata[stepId], side);
        if (file) dropped.add(file);
      }
      delete metadata[stepId];
    }
    used = new Set(
      Object.values(metadata).flatMap((entry) => [schemaFile(entry, 'sourceBody'), schemaFile(entry, 'targetBody')].filter((f): f is string => !!f)),
    );
  });
  for (const stepId of stepIds) if (names.includes(`${stepId}.xsl`)) await files.remove(`${stepId}.xsl`);
  // ECHO's schema files: from the flow's spec, or from the approved API a call picks (callSchemas).
  for (const file of dropped) if (!used.has(file) && (isGeneratedSchemaName(file) || file.startsWith('api-'))) await files.remove(file);
}
